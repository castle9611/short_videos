import {mkdir,readFile,writeFile,copyFile} from 'node:fs/promises';
import path from 'node:path';
import {build} from 'esbuild';
const destination=path.resolve('android/app/build/generated/webAssets/web');
await mkdir(destination,{recursive:true});
for(const filename of ['index.html','style.css','app.js','zip.js'])await copyFile(path.resolve('web',filename),path.join(destination,filename));
const config={apiBase:'https://shiying-api.castle9611-shiying.workers.dev',persistSession:true};
await writeFile(path.join(destination,'config.js'),'window.APP_CONFIG = '+JSON.stringify(config)+';\n');
let html=await readFile(path.join(destination,'index.html'),'utf8');
html=html.replace('</head>','<link rel="stylesheet" href="./mobile.css"></head>');
html=html.replace('<script src="./app.js" defer>','<script src="./device-parser.js" defer></script><script src="./native-ui.js" defer></script><script src="./native-downloads.js" defer></script><script src="./app.js" defer>');
await writeFile(path.join(destination,'index.html'),html);
await copyFile(path.resolve('android/native-downloads.js'),path.join(destination,'native-downloads.js'));
await copyFile(path.resolve('android/native-ui.js'),path.join(destination,'native-ui.js'));
await copyFile(path.resolve('android/mobile.css'),path.join(destination,'mobile.css'));
await copyFile(path.resolve('config/media-hosts.json'),path.join(destination,'media-hosts.json'));
await copyFile(path.resolve('config/parser-hosts.json'),path.join(destination,'parser-hosts.json'));
await build({entryPoints:['android/device-parser.mjs'],bundle:true,format:'iife',globalName:'ShiyingDeviceParser',platform:'browser',target:'chrome90',outfile:path.join(destination,'device-parser.js'),minify:true});
await copyFile(path.resolve('LICENSE'),path.join(destination,'..','LICENSE'));
console.log('Bundled frontend only. Backend: '+config.apiBase);
